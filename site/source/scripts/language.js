function setLang(lang) {
   const dictionary = T[lang] || T.ru;
   currentLang = T[lang] ? lang : "ru";
   try {
      localStorage.setItem("mirokitLang", currentLang);
   } catch {
      // The language still applies to the current page when storage is blocked.
   }
   document.documentElement.lang = currentLang;
   document.querySelectorAll("[data-key]").forEach((element) => {
      const value = dictionary[element.dataset.key];
      if (value !== undefined && element.dataset.i18nMode === "text") {
         const textNode = [...element.childNodes].find((node) => node.nodeType === Node.TEXT_NODE && node.textContent.trim());
         if (textNode) textNode.textContent = ` ${value}`;
         else element.append(document.createTextNode(value));
      } else if (value !== undefined && !element.dataset.i18nAttr) element.innerHTML = value;
      if (value !== undefined && element.dataset.i18nAttr) element.setAttribute(element.dataset.i18nAttr, value);
   });
   applyLanguageAttributes(dictionary);
   document.querySelectorAll(".lang-btn").forEach((button) => button.classList.toggle("on", button.dataset.lang === currentLang));
   document.querySelectorAll("[data-lang-select]").forEach((select) => {
      select.value = currentLang;
   });
   syncLanguageThemeLabels(dictionary);
   document.dispatchEvent(new CustomEvent("mirokit:languagechange", { detail: { lang: currentLang } }));
}

document.querySelectorAll(".lang-btn").forEach((button) => button.addEventListener("click", () => setLang(button.dataset.lang)));
document.querySelectorAll("[data-lang-select]").forEach((select) => select.addEventListener("change", () => setLang(select.value)));
setLang(currentLang);
