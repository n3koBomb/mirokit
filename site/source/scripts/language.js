/**
 * Select the initial language from the host that opened the site.
 *
 * Development hosts are German by default. Russian domains are always
 * Russian. On .com domains, only German and English device locales are
 * recognised; every other locale falls back to English.
 */
function detectInitialLanguage(hostname = window.location.hostname, browserLanguage = window.navigator.language) {
   const host = String(hostname || "")
      .toLowerCase()
      .replace(/\.$/, "");
   const deviceLanguage = String(browserLanguage || "").toLowerCase();

   if (host === "localhost" || host === "127.0.0.1" || host === "::1" || host === "[::1]") return "de";
   if (host.endsWith(".ru")) return "ru";
   if (host.endsWith(".com")) {
      if (deviceLanguage.startsWith("de")) return "de";
      if (deviceLanguage.startsWith("en")) return "en";
      return "en";
   }

   return "en";
}

let currentLang = detectInitialLanguage();

function applyLanguageAttributes(dictionary) {
   document.querySelectorAll("[data-i18n-attrs]").forEach((element) => {
      element.dataset.i18nAttrs.split(",").forEach((definition) => {
         const [attribute, key] = definition.split(":").map((part) => part.trim());
         if (attribute && key && dictionary[key] !== undefined) element.setAttribute(attribute, dictionary[key]);
      });
   });
}

function syncLanguageThemeLabels(dictionary) {
   document.querySelectorAll("[data-theme-toggle]").forEach((toggle) => {
      const isDark = document.documentElement.dataset.theme === "dark";
      const label = dictionary[isDark ? "theme_light" : "theme_dark"];
      if (!label) return;
      toggle.setAttribute("aria-label", label);
      toggle.setAttribute("title", label);
      const text = toggle.querySelector(".theme-toggle-label");
      if (text) text.textContent = label;
   });
}

